import * as fs from "node:fs";
import path from "node:path";
import { createHash } from "node:crypto";

const root = import.meta.dir, skill = path.join(root, "session-bridge"), version = (await Bun.file(path.join(root, "package.json")).json()).version;
await Bun.write(path.join(skill, "LICENSE"), await Bun.file(path.join(root, "LICENSE")).text());
const docs = ["SKILL.md", "LICENSE", "agents/openai.yaml", "references/commands.md", "references/protocol.md", "references/providers.md"];
const assets: Record<string, string> = {};
for (const name of docs) assets[name] = await Bun.file(path.join(skill, name)).text();
const packages = ["age-encryption", "@noble/ciphers", "@noble/curves", "@noble/hashes", "@noble/post-quantum", "@scure/base", "skills", "@vercel/detect-agent", "nostics", "tar", "yaml", "@isaacs/fs-minipass", "minipass", "minizlib", "chownr", "yallist",
  "@noble/post-quantum/node_modules/@noble/curves", "@noble/post-quantum/node_modules/@noble/hashes"];
const licenses = ["Session Bridge " + version + " — bundled third-party notices\n\nBuild/runtime sources: https://github.com/oven-sh/bun/tree/bun-v" + Bun.version +
  "\nEncryption sources: https://github.com/FiloSottile/typage/tree/v0.3.1\nDependencies are fixed by bun.lock.\n",
  "=== Bun " + Bun.version + " runtime licensing ===\n" + await Bun.file(path.join(root, "licenses/bun-runtime.txt")).text()];
for (const name of packages) {
  const dir = path.join(root, "node_modules", name), meta = await Bun.file(path.join(dir, "package.json")).json();
  const license = ["LICENSE", "LICENSE.md"].map(n => path.join(dir, n)).find(p => fs.existsSync(p));
  if (!license) throw new Error("Missing dependency license: " + name);
  licenses.push("=== " + meta.name + "@" + meta.version + " (" + meta.license + ") ===\n" + await Bun.file(license).text());
}
licenses.push(await Bun.file(path.join(root, "node_modules/skills/ThirdPartyNoticeText.txt")).text());
assets["THIRD_PARTY_LICENSES.txt"] = licenses.join("\n\n");
await Bun.write(path.join(skill, "THIRD_PARTY_LICENSES.txt"), assets["THIRD_PARTY_LICENSES.txt"]);
await Bun.write(path.join(root, "bun-src/embedded.ts"), "// Generated by build.ts from the Skill documents and dependency licenses.\nexport const EMBEDDED_FILES: Record<string, string> = " + JSON.stringify(assets) + ";\n");

async function bundle(standalone: boolean) {
  const result = await Bun.build({ entrypoints: [path.join(root, "bun-src/cli.ts")], target: "bun", format: "esm", minify: false,
    define: { __SB_STANDALONE__: String(standalone) } });
  if (!result.success) throw new AggregateError(result.logs, "Bun build failed");
  return result.outputs[0];
}
const source = path.join(skill, "scripts/session-bridge.ts"); await Bun.write(source, await bundle(false));
console.log(JSON.stringify({ status: "built_source", version, file: source, runtime_npm_install_required: false }));

if (Bun.argv.includes("--standalone")) {
  const targets: Record<string, string> = { "macos-arm64": "bun-darwin-arm64", "macos-x64": "bun-darwin-x64-baseline", "windows-x64": "bun-windows-x64-baseline" };
  const requested = Bun.argv.find(a => a.startsWith("--targets="))?.slice("--targets=".length).split(",") || Object.keys(targets);
  if (!requested.length || requested.some(t => !Object.hasOwn(targets, t))) throw new Error("Unknown standalone target");
  const dest = path.join(root, "dist/standalone-" + version), intermediate = path.join(root, "dist/.build/cli-native.js");
  fs.mkdirSync(dest, { recursive: true }); await Bun.write(intermediate, await bundle(true));
  const artifacts = [];
  for (const name of requested) {
    const file = path.join(dest, "session-bridge-" + name + (name.startsWith("windows-") ? ".exe" : ""));
    const command = [process.execPath, "build", "--compile", "--target=" + targets[name], "--no-compile-autoload-dotenv", "--no-compile-autoload-bunfig",
      "--no-compile-autoload-tsconfig", "--no-compile-autoload-package-json", intermediate, "--outfile", file];
    // Bun 1.3.6 can cross-compile PE on macOS; editing Windows version resources requires a Windows build host.
    if (name.startsWith("windows-") && process.platform === "win32") command.push("--windows-title=Session Bridge", "--windows-version=" + version + ".0", "--windows-description=Portable encrypted agent task handoffs");
    const child = Bun.spawn(command, { cwd: root, stdout: "inherit", stderr: "inherit" });
    if (await child.exited !== 0) throw new Error("Standalone compile failed: " + name);
    if (process.platform === "darwin" && name.startsWith("macos-")) {
      const sign = Bun.spawnSync(["/usr/bin/codesign", "--force", "--sign", "-", file], { stdout: "pipe", stderr: "pipe" });
      if (sign.exitCode !== 0) throw new Error("Ad-hoc macOS signing failed");
    }
    const bytes = await Bun.file(file).arrayBuffer(), sha256 = createHash("sha256").update(new Uint8Array(bytes)).digest("hex");
    await Bun.write(file + ".sha256", sha256 + "  " + path.basename(file) + "\n");
    const artifact = { target: name, compiler_target: targets[name], file: path.basename(file), bytes: bytes.byteLength, sha256, runtime_dependencies: [] };
    artifacts.push(artifact); console.log(JSON.stringify({ status: "built_executable", ...artifact }));
  }
  if (requested.includes("macos-arm64") && requested.includes("macos-x64")) {
    if (process.platform !== "darwin") throw new Error("The universal macOS release needs Apple's lipo and codesign on a Mac build host.");
    const file = path.join(dest, "session-bridge-macos-universal"), slices = ["macos-arm64", "macos-x64"].map(t => path.join(dest, "session-bridge-" + t));
    for (const command of [["/usr/bin/xcrun", "lipo", "-create", ...slices, "-output", file], ["/usr/bin/codesign", "--force", "--sign", "-", file]]) {
      const result = Bun.spawnSync(command, { stdout: "pipe", stderr: "pipe" });
      if (result.exitCode !== 0) throw new Error("Universal macOS build/signing failed");
    }
    const bytes = await Bun.file(file).arrayBuffer(), sha256 = createHash("sha256").update(new Uint8Array(bytes)).digest("hex");
    await Bun.write(file + ".sha256", sha256 + "  " + path.basename(file) + "\n");
    const artifact = { target: "macos-universal", compiler_target: "arm64+x64-baseline", file: path.basename(file), bytes: bytes.byteLength, sha256, runtime_dependencies: [] };
    artifacts.push(artifact); console.log(JSON.stringify({ status: "built_executable", ...artifact }));
    // Keep just one Mac executable in the default release. Thin build products stay in the build cache.
    for (const name of ["macos-arm64", "macos-x64"]) {
      for (const suffix of ["", ".sha256"]) fs.renameSync(path.join(dest, "session-bridge-" + name + suffix), path.join(root, "dist/.build/session-bridge-" + name + suffix));
    }
    for (let i = artifacts.length - 1; i >= 0; i--) if (["macos-arm64", "macos-x64"].includes(artifacts[i].target)) artifacts.splice(i, 1);
  }
  await Bun.write(path.join(dest, "manifest.json"), JSON.stringify({ version, bun: Bun.version, crypto: "age-encryption@0.3.1", skills: "1.9.0", detect_agent: "1.2.7", artifacts }, null, 2) + "\n");
}
